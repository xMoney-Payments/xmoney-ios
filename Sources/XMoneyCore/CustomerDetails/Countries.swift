    private static let index: [String: Country] = {
        var map: [String: Country] = [:]
        for country in all {
            map[country.code] = country
        }
        return map
    }()

    package static func byCode(_ code: String) -> Country? {
        index[code.trimmingCharacters(in: .whitespacesAndNewlines).uppercased()]
    }

    /// Flag emoji for an ISO 3166-1 alpha-2 code. Empty when the code is not two letters.
    package static func flagEmoji(code: String) -> String {
        let upper = code.trimmingCharacters(in: .whitespacesAndNewlines).uppercased()
        guard upper.count == 2, upper.unicodeScalars.allSatisfy({ $0.value >= 65 && $0.value <= 90 }) else {
            return ""
        }
        return upper.unicodeScalars.map { scalar in
            String(UnicodeScalar(127397 + scalar.value)!)
        }.joined()
    }

    package static func localizedName(_ country: Country, locale: String) -> String {
        let language = locale.split(separator: "-").first.map(String.init) ?? locale
        if language == "en" { return country.name }
        let localized = Locale(identifier: locale).localizedString(forRegionCode: country.code)
        if let localized, !localized.isEmpty, localized.caseInsensitiveCompare(country.code) != .orderedSame {
            return localized
        }
        return country.name
    }
